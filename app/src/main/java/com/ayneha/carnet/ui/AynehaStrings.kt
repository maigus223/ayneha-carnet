    /** Convertit un entier en chiffres AYNEHA (ex: 32 → ) */
    fun toAynehaDigits(n: Int): String {
        if (n < 0) return n.toString()
        if (n == 0) return digits[0]
        val sb = StringBuilder()
        var x = n
        val stack = ArrayDeque<Int>()
        while (x > 0) {
            stack.addFirst(x % 10)
            x /= 10
        }
        stack.forEach { sb.append(digits[it]) }
        return sb.toString()
    }

